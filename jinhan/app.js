function isPlaceholder(value) {
  return typeof value === "string" && value.trim().startsWith("[") && value.trim().endsWith("]");
}

function resolveImageSource(candidates, fallbackSrc) {
  return new Promise((resolve) => {
    let index = 0;

    function tryNext() {
      if (index >= candidates.length) {
        resolve(fallbackSrc);
        return;
      }

      const src = candidates[index];
      const probe = new Image();

      probe.onload = () => resolve(src);
      probe.onerror = () => {
        index += 1;
        tryNext();
      };
      probe.src = src;
    }

    tryNext();
  });
}

function setTextContent(lang) {
  const data = profileData[lang];

  copyFields.forEach((field) => {
    document.querySelectorAll(`[data-copy="${field}"]`).forEach((node) => {
      node.textContent = data[field];
    });
  });

  document.querySelectorAll(".contact-value").forEach((node) => {
    node.classList.toggle("is-placeholder", isPlaceholder(node.textContent));
  });

  document.title = data.pageTitle;
  document.documentElement.lang = lang;
  document.body.dataset.lang = lang;
}

function renderTags(lang) {
  const tagRow = document.getElementById("systemTags");
  tagRow.innerHTML = "";

  profileData[lang].tags.forEach((tag) => {
    const span = document.createElement("span");
    span.className = "tag";
    span.textContent = tag;
    tagRow.appendChild(span);
  });
}

function renderLinks(lang) {
  const container = document.getElementById("platformLinks");
  container.innerHTML = "";

  profileData[lang].links.forEach((link) => {
    const anchor = document.createElement("a");
    anchor.className = "platform-link";
    anchor.href = link.url;
    anchor.target = "_blank";
    anchor.rel = "noreferrer noopener";

    const label = document.createElement("strong");
    label.textContent = link.label;

    const note = document.createElement("span");
    note.textContent = link.note;

    anchor.append(label, note);
    container.appendChild(anchor);
  });
}

function renderList(elementId, items) {
  const list = document.getElementById(elementId);
  list.innerHTML = "";

  items.forEach((item) => {
    const li = document.createElement("li");
    li.textContent = item;
    list.appendChild(li);
  });
}

function renderStats(lang) {
  const grid = document.getElementById("highlightCards");
  grid.innerHTML = "";

  profileData[lang].stats.forEach((stat) => {
    const article = document.createElement("article");
    article.className = "highlight-card";

    const value = document.createElement("span");
    value.className = "highlight-value";
    if (isPlaceholder(stat.value)) {
      value.classList.add("is-placeholder");
    }
    value.textContent = stat.value;

    const label = document.createElement("span");
    label.className = "highlight-label";
    label.textContent = stat.label;

    const note = document.createElement("span");
    note.className = "highlight-note";
    note.textContent = stat.note;

    article.append(value, label, note);
    grid.appendChild(article);
  });
}

function renderGallery(lang) {
  const grid = document.getElementById("galleryGrid");
  grid.innerHTML = "";

  profileData[lang].galleryItems.forEach((item) => {
    const figure = document.createElement("figure");
    figure.className = "gallery-card";
    if (item.fit === "contain") {
      figure.classList.add("gallery-card-doc");
    }

    const image = document.createElement("img");
    image.src = item.src;
    image.alt = item.title;
    image.loading = "lazy";

    const caption = document.createElement("figcaption");
    const title = document.createElement("strong");
    title.textContent = item.title;
    const text = document.createElement("p");
    text.textContent = item.caption;

    caption.append(title, text);
    figure.append(image, caption);
    grid.appendChild(figure);
  });
}

